STATUS_COLORS = {
    "Выполнено в срок": "#2ca02c",  # Зеленый
    "В работе": "#1f77b4",          # Синий
    "Сдвинуты сроки": "#ff7f0e",    # Оранжевый / желто-оранжевый
    "Перенос на 2027": "#d62728"    # Красный
}

GROUP_COLORS = {
    "DEV": "#3366CC",
    "CLI": "#109618",
    "FAC": "#FF9900",
    "SCI": "#DC3912",
    "EDU": "#990099"
}

def render_gantt(data_subset, color_mode="Status"):
    if data_subset.empty:
        st.warning("Нет задач, соответствующих выбранным параметрам.")
        return

    data_subset = data_subset.sort_values(by=["Group", "ID", "Start"], ascending=[True, True, True])
    project_order = list(reversed(data_subset["Project"].unique().tolist()))
    
    color_col = "Status" if color_mode == "Status" else "Group"
    cmap = STATUS_COLORS if color_mode == "Status" else GROUP_COLORS

    fig = px.timeline(
        data_subset,
        x_start="Start",
        x_end="End",
        y="Project",
        color=color_col,
        text=None,  # Убираем фиксированный накладывающийся текст
        color_discrete_map=cmap,
        category_orders={"Project": project_order},
        hover_data={
            "Project": True,
            "Task": True,
            "Lead": True,
            "Type": True,
            "Status": True,
            "Result": True,
            "Start": False,
            "End": False
        }
    )

    # Кастомный подробный Tooltip
    fig.update_traces(
        hovertemplate="<b>%{y}</b><br>" +
                      "<b>Задача:</b> %{customdata[1]}<br>" +
                      "<b>Ответственный:</b> %{customdata[2]}<br>" +
                      "<b>Тип:</b> %{customdata[3]} | <b>Статус:</b> %{customdata[4]}<br>" +
                      "<b>Ожидаемый результат:</b> %{customdata[5]}<br>" +
                      "<b>Период:</b> %{x|%d.%m.%Y} — %{base|%d.%m.%Y}<extra></extra>"
    )

    fig.update_yaxes(autorange="reversed", title=None)
    
    # Линия «Сегодня»
    current_date = datetime.now()
    fig.add_vline(
        x=current_date,
        line_width=2,
        line_dash="dash",
        line_color="#E02424",
        annotation_text="Сегодня",
        annotation_position="top left",
        annotation_font_color="#E02424",
        annotation_font_size=12
    )

    calc_height = max(450, len(project_order) * 44)
    fig.update_layout(
        height=calc_height,
        xaxis=dict(
            tickformat="%b %Y",
            dtick="M1",
            showgrid=True,
            gridcolor="#E5E7EB",
            title="Шкала времени (Месяцы / Годы)"
        ),
        margin=dict(l=15, r=15, t=30, b=15),
        legend=dict(
            orientation="h",
            yanchor="bottom",
            y=1.02,
            xanchor="right",
            x=1,
            title=None
        ),
        hoverlabel=dict(bgcolor="white", font_size=12)
    )
    st.plotly_chart(fig, use_container_width=True)

