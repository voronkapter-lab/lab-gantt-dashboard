def render_gantt(data_subset, color_mode="Status"):
    if data_subset.empty:
        st.warning("Нет задач, соответствующих выбранным параметрам.")
        return

    data_subset = data_subset.sort_values(by=["OpManager", "ID", "Start"], ascending=[True, True, True])
    project_order = list(reversed(data_subset["Project"].unique().tolist()))
    
    color_col = "Status" if color_mode == "Status" else "OpManager"
    cmap = STATUS_COLORS if color_mode == "Status" else MANAGER_COLORS

    fig = px.timeline(
        data_subset,
        x_start="Start",
        x_end="End",
        y="Project",
        color=color_col,
        text=None,
        color_discrete_map=cmap,
        category_orders={"Project": project_order},
        hover_data={
            "OpManager": True,
            "Project": True,
            "Task": True,
            "Lead": True,
            "Type": True,
            "Status": True,
            "Result": True,
            "Start": False,
            "End": False
        }
    )

    # Исправленный Tooltip с контрастным стилем и верным порядком дат (Начало — Конец)
    fig.update_traces(
        hovertemplate="<b style='font-size:13px;'>%{y}</b><br><br>" +
                      "<b>Оперменеджер:</b> %{customdata[0]}<br>" +
                      "<b>Задача:</b> %{customdata[2]}<br>" +
                      "<b>Ответственный:</b> %{customdata[3]}<br>" +
                      "<b>Тип:</b> %{customdata[4]} | <b>Статус:</b> %{customdata[5]}<br>" +
                      "<b>Результат:</b> %{customdata[6]}<br>" +
                      "<b>Период:</b> %{base|%d.%m.%Y} — %{x|%d.%m.%Y}<extra></extra>"
    )

    fig.update_yaxes(autorange="reversed", title=None)
    
    current_date = datetime.now()
    fig.add_vline(
        x=current_date,
        line_width=2,
        line_dash="dash",
        line_color="#E02424",
        annotation_text="Сегодня",
        annotation_position="top left",
        annotation_font_color="#E02424",
        annotation_font_size=12
    )

    calc_height = max(420, len(project_order) * 44)
    fig.update_layout(
        height=calc_height,
        xaxis=dict(
            tickformat="%b %Y",
            dtick="M1",
            showgrid=True,
            gridcolor="rgba(255, 255, 255, 0.12)",
            title="Шкала времени (Месяцы / Годы)"
        ),
        margin=dict(l=15, r=15, t=30, b=15),
        legend=dict(
            orientation="h",
            yanchor="bottom",
            y=1.02,
            xanchor="right",
            x=1,
            title=None
        ),
        hoverlabel=dict(
            bgcolor="#1E293B",     # Контрастный темно-серый фон
            font_color="#F8FAFC",  # Гарантированно белый/светлый шрифт
            font_size=12,
            bordercolor="#475569"  # Четкая рамка окна
        )
    )
    st.plotly_chart(fig, use_container_width=True)
