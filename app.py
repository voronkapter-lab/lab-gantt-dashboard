def render_project_passport_cards(manager_name, filtered_projects):
    st.markdown("#### 📌 Сводная карточка проекта")
    available_projects = [p for p in filtered_projects if p in PROJECT_PASSPORTS]
    
    if not available_projects:
        st.info("Нет детальных карточек для выбранных проектов в фильтре.")
        return
        
    selected_p = st.selectbox(
        "Выберите проект для просмотра подробностей:",
        options=available_projects,
        key=f"passport_select_{manager_name}"
    )
    
    card = PROJECT_PASSPORTS[selected_p]
    
    c1, c2, c3, c4 = st.columns(4)
    with c1:
        st.markdown("**🎯 Цель и продукт**")
        st.write(card["Цель"])
